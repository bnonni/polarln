const isVariable = (value: ExampleValue): value is Variable =>
  !!value && typeof value === 'object' && !Array.isArray(value);

// Get the method name of a tool name (open_channel gives openChannel)
const methodName = (tool: string) =>
  tool.replace(underscoreLetter, (_, letter: string) => letter.toUpperCase());

// Add a period to a text that has no end mark, as the CLI help does
const sentence = (text: string) =>
  !text || sentenceEnd.test(text) ? text : `${text}.`;

// Get the first sentence of a tool description, as the CLI help does
const summaryOf = (tool: PolarTool) =>
  sentence(tool.description.split(sentenceStop)[0] || '');

// Get the arguments of a tool, the required arguments first, as in the help
const argumentsOf = (tool: PolarTool) => {
  const required = tool.inputSchema.required || [];

  const entries = Object.entries(tool.inputSchema.properties) as [
    string,
    Property,
  ][];

  return [
    ...entries.filter(([name]) => required.includes(name)),
    ...entries.filter(([name]) => !required.includes(name)),
  ].map(([name, property]) => {
    return {isRequired: required.includes(name), name, property};
  });
};

const isJson = (property: Property) =>
  property.type === 'array' || property.type === 'object';

// Get the value name of a flag, as the CLI help shows it
const valueNameOf = (property: Property) =>
  isJson(property) ? 'json' : property.type || 'value';

// Get the type of a flag value for the flags table
const typeOf = (property: Property) => {
  switch (property.type) {
    case 'array':
      return 'JSON array';

    case 'object':
      return 'JSON object';

    default:
      return property.type || 'value';
  }
};

// Escape a table cell text
const cell = (text: string) => text.replaceAll('|', '\\|');

const code = (value: unknown) => `\`${String(value)}\``;

const plural = (count: number) => (count === 1 ? 'command' : 'commands');

// Get the markdown of a table, with the columns aligned as oxfmt aligns them
const table = (header: string[], rows: string[][]) => {
  const widths = header.map((title, i) => {
    return Math.max(3, title.length, ...rows.map(row => row[i]?.length || 0));
  });

  const line = (cells: string[]) =>
    `| ${cells.map((text, i) => text.padEnd(widths[i] || 0)).join(' | ')} |`;

  return [
    line(header),
    line(widths.map(width => '-'.repeat(width))),
    ...rows.map(line),
  ].join('\n');
};

// Get the notes of a value: the allowed values and the limits
const limitsOf = (property: Property) => {
  return [
    !!property.enum ? `Values: ${property.enum.map(code).join(', ')}.` : '',
    property.minimum !== undefined ? `Minimum: ${code(property.minimum)}.` : '',
    property.maximum !== undefined ? `Maximum: ${code(property.maximum)}.` : '',
  ];
};

// Get the keys of the objects in an array argument, as the CLI help does
const itemKeysOf = (property: Property) => {
  const keys = Object.keys(property.items?.properties || {});
  const required = property.items?.required || [];

  if (!keys.length) {
    return '';
  }

  const names = keys.map(key => {
    return required.includes(key) ? `${code(key)} (required)` : code(key);
  });

  return `Item keys: ${names.join(', ')}.`;
};

// Get the description cell of a flag. The text of Polar comes first. A
// default shows only if the Polar text does not already give it.
const flagNotes = (name: string, property: Property) => {
  const description = property.description || '';
  const isBoolean = property.type === 'boolean';
  const hasDefault = property.default !== undefined;

  const notes = [
    sentence(description),
    ...limitsOf(property),
    property.type === 'array' ? itemKeysOf(property) : '',
    hasDefault && !/\bdefault\b/i.test(description)
      ? `Default: ${code(JSON.stringify(property.default))}.`
      : '',
    isBoolean && property.default !== false
      ? `Use ${code(`--no-${flagName(name)}`)} for false.`
      : '',
  ];

  return cell(notes.filter(Boolean).join(' '));
};

// Get the table of the keys of the objects in an array argument
const itemsTable = (name: string, property: Property) => {
  const required = property.items?.required || [];

  const entries = Object.entries(property.items?.properties || {});

  if (!entries.length) {
    return [];
  }

  const rows = entries.map(([key, item]) => {
    const notes = [sentence(item.description || ''), ...limitsOf(item)];

    return [
      code(key),
      typeOf(item),
      required.includes(key) ? 'yes' : 'no',
      cell(notes.filter(Boolean).join(' ')),
    ];
  });

  return [
    `Each item of ${code(`--${flagName(name)}`)} is a JSON object with these keys:`,
    '',
    table(['Key', 'Type', 'Required', 'Description'], rows),
    '',
  ];
};

// Quote a text for a POSIX shell
const shellText = (text: string) =>
  safeShellText.test(text) ? text : `'${text.replaceAll("'", "'\\''")}'`;

// Get the JSON text of a value, with a space after each colon and comma
const jsonText = (value: unknown): string => {
  if (Array.isArray(value)) {
    return `[${value.map(jsonText).join(', ')}]`;
  }

  if (!!value && typeof value === 'object') {
    const entries = Object.entries(value).map(([key, item]) => {
      return `${JSON.stringify(key)}: ${jsonText(item)}`;
    });

    return `{${entries.join(', ')}}`;
  }

  return JSON.stringify(value);
};

// Get the TypeScript text of a value, in the Prettier style of the repo
const tsText = (value: unknown): string => {
  if (Array.isArray(value)) {
    return `[${value.map(tsText).join(', ')}]`;
  }

  if (!!value && typeof value === 'object') {
    const entries = Object.entries(value).map(([key, item]) => {
      return `${key}: ${tsText(item)}`;
    });

    return `{${entries.join(', ')}}`;
  }

  if (typeof value === 'string') {
    return `'${value.replaceAll('\\', '\\\\').replaceAll("'", "\\'")}'`;
  }

  return String(value);
};

// Join command parts on lines of at most the line width, with a backslash
// at the end of each line that continues
const shellLines = (parts: string[]) => {
  const lines: string[] = [];

  parts.forEach(part => {
    const last = lines.length - 1;
    const current = lines[last];

    if (current !== undefined && `${current} ${part} \\`.length <= lineWidth) {
      lines[last] = `${current} ${part}`;
    } else {
      lines.push(!lines.length ? part : `  ${part}`);
    }
  });

  return lines.join(' \\\n');
};

// Get the example arguments of a tool in the order of the usage
const exampleEntriesOf = (doc: CommandDoc) => {
  const names = argumentsOf(doc.tool).map(({name}) => name);

  return names
    .filter(name => Object.hasOwn(doc.example, name))
    .map(name => [name, doc.example[name]] as [string, ExampleValue]);
};

/** Get the command line words of an example, after the command name

  A variable is its shell text: "$invoice"

  <Command Doc Object>

  @returns
  [<Command Line Argument String>]
*/
export const exampleArgv = (doc: CommandDoc) => {
  return exampleEntriesOf(doc).flatMap(([name, value]) => {
    const flag = `--${flagName(name)}`;

    if (typeof value === 'boolean') {
      return [value ? flag : `--no-${flagName(name)}`];
    }

    if (isVariable(value)) {
      return [flag, `$${name}`];
    }

    if (Array.isArray(value)) {
      return [flag, jsonText(value)];
    }

    return [flag, String(value)];
  });
};

/** Get the tool arguments that the example command line gives

  A variable is its shell text: "$invoice"

  <Command Doc Object>

  @returns
  {<Argument Name String>: <Argument Value>}
*/
export const exampleArgs = (doc: CommandDoc) => {
  const args: {[name: string]: unknown} = {};

  exampleEntriesOf(doc).forEach(([name, value]) => {
    args[name] = isVariable(value) ? `$${name}` : value;
  });

  return args;
};

// Get the shell example of a command
const shellExample = (doc: CommandDoc) => {
  const entries = exampleEntriesOf(doc);

  const comments = entries
    .filter(([, value]) => isVariable(value))
    .map(([name, value]) => `# $${name}: ${(value as Variable).variable}`);

  const parts = entries.map(([name, value]) => {
    const flag = `--${flagName(name)}`;

    if (typeof value === 'boolean') {
      return value ? flag : `--no-${flagName(name)}`;
    }

    if (isVariable(value)) {
      return `${flag} "$${name}"`;
    }

    if (Array.isArray(value)) {
      return `${flag} ${shellText(jsonText(value))}`;
    }

    return `${flag} ${shellText(String(value))}`;
  });

  return [...comments, shellLines([`polarln ${doc.command}`, ...parts])];
};

// Get the TypeScript example of a command, in the Prettier style
const sdkExample = (doc: CommandDoc) => {
  const entries = exampleEntriesOf(doc);

  const props = [
    'polar',
    ...entries.map(([name, value]) => {
      return isVariable(value) ? name : `${name}: ${tsText(value)}`;
    }),
  ];

  const line = `await ${doc.method}({${props.join(', ')}});`;

  if (line.length <= lineWidth) {
    return line;
  }

  // Prettier puts a long string on its own line after the key
  const lines = [['polar', undefined], ...entries].map(([name, value]) => {
    if (value === undefined || isVariable(value)) {
      return `  ${name},`;
    }

    const text = tsText(value);
    const prop = `  ${name}: ${text},`;

    const isLong = prop.length > lineWidth && typeof value === 'string';

    return isLong ? `  ${name}:\n    ${text},` : prop;
  });

  return [`await ${doc.method}({`, ...lines, '});'].join('\n');
};

// Get the usage line of a command
const usage = (doc: CommandDoc) => {
  const parts = argumentsOf(doc.tool).map(({isRequired, name, property}) => {
    const flag = `--${flagName(name)}`;

    const text =
      property.type === 'boolean' ? flag : `${flag} <${valueNameOf(property)}>`;

    return isRequired ? text : `[${text}]`;
  });

  return shellLines([`polarln ${doc.command}`, ...parts]);
};

// Get the flags section of a command
const flagsSection = (doc: CommandDoc) => {
  const args = argumentsOf(doc.tool);

  if (!args.length) {
    return ['This command has no flags.', ''];
  }

  const rows = args.map(({isRequired, name, property}) => {
    return [
      code(`--${flagName(name)}`),
      typeOf(property),
      isRequired ? 'yes' : 'no',
      flagNotes(name, property),
    ];
  });

  return [
    table(['Flag', 'Type', 'Required', 'Description'], rows),
    '',
    ...args.flatMap(({name, property}) => {
      return property.type === 'array' ? itemsTable(name, property) : [];
    }),
  ];
};

// Get the backends section of a command
const backendsSection = (doc: CommandDoc) => {
  const docker = doc.docker
    ? '- Docker: yes.'
    : '- Docker: no (`501 PolarToolNotSupported`).';

  const appCheck = !doc.docker
    ? []
    : doc.checksApp
      ? [
          '- Polar app check on Docker: yes. In the Polar home, the command ' +
            'first checks that the Polar app does not run. See ' +
            '[Polar app check](../polar-app.md#polar-app-check).',
        ]
      : [
          '- Polar app check on Docker: no. The command does not change ' +
            'files or containers.',
        ];

  return [
    '## Backends',
    '',
    '- Bridge: yes.',
    docker,
    ...appCheck,
    '',
    'To select the backend, see [Backends](../cli.md#backends).',
    '',
  ];
};

// Get the SDK section of a command
const sdkSection = (doc: CommandDoc) => {
  const args = argumentsOf(doc.tool);

  const jsonFlags = args.filter(({property}) => isJson(property));

  const argsLine = !args.length
    ? 'Its only argument is `polar`.'
    : 'Its arguments are `polar` and the flags in camelCase.';

  const jsonLines = jsonFlags.map(({name, property}) => {
    return `The ${code(name)} argument is an ${property.type}, not a JSON text.`;
  });

  return [
    '## SDK',
    '',
    [
      `The method is ${code(doc.method)}.`,
      argsLine,
      ...jsonLines,
      'See [Methods](../sdk.md#methods).',
    ].join(' '),
    '',
    '```ts',
    sdkExample(doc),
    '```',
    '',
  ];
};

/** Get the documentation data of each command, in the order of the index

  The commands are the bundled Polar tools and the local polarln tools

  @throws
  <Error> // A tool has no example, or no SDK method

  @returns
  [<Command Doc Object>]
*/
export const commandDocs = (): CommandDoc[] => {
  const localNames = localTools.map(({name}) => name);

  const tools: PolarTool[] = [
    ...bundledTools.filter(({name}) => !localNames.includes(name)),
    ...localTools.map(({description, inputSchema, name}) => {
      return {description, inputSchema, name};
    }),
  ];

  const docs = tools.map((tool): CommandDoc => {
    const example = examples[tool.name];
    const method = methodName(tool.name);
    const isLocal = localNames.includes(tool.name);

    const group = isLocal
      ? localGroup
      : groups.find(([, module]) => Object.hasOwn(module, method))?.[0];

    if (!example) {
      throw new Error(`Add an example for ${tool.name} to command_docs.ts`);
    }

    if (!group) {
      throw new Error(`No SDK method ${method} in src/polar_methods`);
    }

    return {
      checksApp: !isLocal && !readNames.includes(tool.name),
      command: commandName(tool.name),
      docker: isLocal || dockerNames.includes(tool.name),
      example,
      group,
      method,
      tool,
    };
  });

  const order = [...groups.map(([title]) => title), localGroup];

  return order.flatMap(title => docs.filter(doc => doc.group === title));
};

/** Get the generated region of a command page, with the marker lines

  The local tools run the SDK method of polarln, so the docker backend
  supports them. getNodeCredentials only reads the networks and the node
  files, so it does not check for the Polar app.

  <Command Doc Object>

  @returns
  <Markdown Region String> // No line break at the end
*/
export const commandRegion = (doc: CommandDoc) => {
  return [
    beginMarker,
    '',
    `# polarln ${doc.command}`,
    '',
    `> ${doc.tool.description}`,
    '',
    '## Usage',
    '',
    '```sh',
    usage(doc),
    '```',
    '',
    '## Flags',
    '',
    ...flagsSection(doc),
    'For the flags of all commands, see ' +
      '[Global flags](../cli.md#global-flags).',
    '',
    ...backendsSection(doc),
    ...sdkSection(doc),
    '## Example',
    '',
    '```sh',
    ...shellExample(doc),
    '```',
    '',
    endMarker,
  ].join('\n');
};

/** Get a new command page: the generated region and an empty notes section

  <Command Doc Object>

  @returns
  <Markdown Page String>
*/
export const newCommandPage = (doc: CommandDoc) =>
  `${commandRegion(doc)}\n\n## Notes\n\nNo notes.\n`;

// Get the line numbers of the marker lines of a page
const markerLines = (lines: string[]) => {
  const begin = lines.indexOf(beginMarker);
  const end = lines.indexOf(endMarker, begin + 1);

  const isValid =
    begin >= 0 &&
    end > begin &&
    lines.lastIndexOf(beginMarker) === begin &&
    lines.lastIndexOf(endMarker) === end;

  return isValid ? {begin, end} : undefined;
};

/** Get the generated region of a page text, with the marker lines

  <Markdown Page String>

  @returns
  <Markdown Region String> // undefined: the page has no valid region
*/
export const regionOf = (page: string) => {
  const lines = page.split('\n');
  const markers = markerLines(lines);

  if (!markers) {
    return undefined;
  }

  return lines.slice(markers.begin, markers.end + 1).join('\n');
};

/** Replace the generated region of a page text

  The text before and after the region does not change

  {
    page: <Markdown Page String>
    region: <Markdown Region String>
  }

  @returns
  <Markdown Page String> // undefined: the page has no valid region
*/
export const replaceRegion = (args: {page: string; region: string}) => {
  const lines = args.page.split('\n');
  const markers = markerLines(lines);

  if (!markers) {
    return undefined;
  }

  return [
    ...lines.slice(0, markers.begin),
    args.region,
    ...lines.slice(markers.end + 1),
  ].join('\n');
};

/** Get the markdown of the command index, docs/commands/README.md

  @returns
  <Markdown Page String>
*/
export const commandsIndex = () => {
  const docs = commandDocs();
  const local = docs.filter(({group}) => group === localGroup);
  const titles = [...new Set(docs.map(({group}) => group))];

  const sections = titles.flatMap(title => {
    const rows = docs
      .filter(({group}) => group === title)
      .map(doc => {
        return [
          `[${code(doc.command)}](${doc.command}.md)`,
          cell(summaryOf(doc.tool)),
          doc.docker ? 'yes' : 'no (501)',
        ];
      });

    return [
      `## ${title}`,
      '',
      table(['Command', 'Description', 'Docker'], rows),
      '',
    ];
  });

  return [
    indexMarker,
    '',
    '# Command reference',
    '',
    `polarln has ${docs.length} commands: ${docs.length - local.length} ` +
      `Polar tools and ${local.length} polarln ${plural(local.length)}. ` +
      'Each page shows the usage, the flags, the backends, the SDK method, ' +
      'and an example of one command.',
    '',
    'The pages come from the bundled Polar tool schemas. With the bridge, ' +
      'the command list comes from the Polar app. Run `polarln --help` to ' +
      'see the commands of your Polar app.',
    '',
    'The Docker column shows if the Docker backend supports the command. On ' +
      'Docker, the other commands give `501 PolarToolNotSupported`.',
    '',
    'For the flags of all commands, see [Global flags](../cli.md#global-flags).',
    '',
    ...sections,
  ].join('\n');
};
